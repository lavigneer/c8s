/**
 * Get screenshot specs for a specific feature
 */
export function getFeatureScreenshots(feature: string): ScreenshotSpec[] {
  return SCREENSHOTS.filter(spec => spec.feature === feature);
}

/**
 * Get all unique features
 */
export function getAllFeatures(): string[] {
  return Array.from(new Set(SCREENSHOTS.map(spec => spec.feature)));
}

/**
 * Get responsive screenshot specs
 */
export function getResponsiveScreenshots(): ScreenshotSpec[] {
  return SCREENSHOTS.filter(spec => spec.responsive === true);
}

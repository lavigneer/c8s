/**
 * Screenshot specifications for documentation
 * Defines all screenshots to capture and their configurations
 */

export interface ScreenshotSpec {
  /** Feature/category name */
  feature: string;
  /** Human-readable screen name */
  screenName: string;
  /** Setup function to navigate to this screen */
  setup: () => Promise<void>;
  /** Optional: CSS selector for element-specific screenshot */
  element?: string;
  /** Optional: Custom filename (without .png) */
  filename?: string;
  /** Optional: Wait for specific selectors before capturing */
  readinessSelectors?: string[];
  /** Optional: Whether to capture responsive variants */
  responsive?: boolean;
  /** Optional: Description for documentation */
  description?: string;
  /** Optional: Wait time in ms before screenshot */
  waitTime?: number;
  /** Optional: Full page screenshot */
  fullPage?: boolean;
}

